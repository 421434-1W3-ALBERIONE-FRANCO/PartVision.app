package com.partvision.catalog.domain;

/**
 * Estado de un producto en el catalogo.
 * BORRADOR: creado desde una extraccion IA sin confirmar (Fase 7).
 * ACTIVO: producto confirmado y operable.
 * INACTIVO: dado de baja logica.
 */
public enum ProductoEstado {
    BORRADOR,
    ACTIVO,
    INACTIVO
}
